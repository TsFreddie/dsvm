import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join } from 'node:path';
import { desktopAppDir } from './nwjs.js';
import { DsvmError, commandExists, mkdirp, rmrf, run, writeTextAtomic } from '../util.js';

export const DESKTOP_ENTRY_NAME = 'dsvm-desktop.desktop';
export const APP_DISPLAY_NAME = 'dsvm desktop';

/** 快捷方式创建结果：建了什么、删了什么，如实回显给用户。 */
export interface ShortcutResult {
  created: string[];
  removed: string[];
  notes: string[];
}

function appIcon(preferred: 'png' | 'svg' | 'ico'): string {
  return join(desktopAppDir(), `icon.${preferred}`);
}

/**
 * 生成 Linux .desktop 文件内容。纯函数，便于单测。
 * 快捷方式直接启动 nw 二进制 + 应用目录，不经过 dsvm（避免图标/WM 归属问题）。
 */
export function linuxDesktopEntry(nwBinary: string, appDir: string, icon: string): string {
  const quote = (value: string): string =>
    /[\s"\\]/.test(value) ? `"${value.replace(/(["\\])/g, '\\$1')}"` : value;
  return [
    '[Desktop Entry]',
    'Type=Application',
    `Name=${APP_DISPLAY_NAME}`,
    'Comment=DeepSeek Harness desktop (dsvm service web UI)',
    `Exec=${quote(nwBinary)} ${quote(appDir)} %U`,
    `TryExec=${nwBinary}`,
    `Icon=${icon}`,
    'Categories=Development;Utility;',
    'Terminal=false',
    '',
  ].join('\n');
}

export function linuxDesktopFile(): string {
  const base =
    process.env.XDG_DATA_HOME ||
    join(homedir(), '.local', 'share');
  return join(base, 'applications', DESKTOP_ENTRY_NAME);
}

async function installLinux(nwBinary: string, appDir: string, result: ShortcutResult): Promise<void> {
  const icon = existsSync(appIcon('png')) ? appIcon('png') : appIcon('svg');
  const file = linuxDesktopFile();
  writeTextAtomic(file, linuxDesktopEntry(nwBinary, appDir, icon), 0o644);
  result.created.push(file);
  // 最佳努力：刷新桌面数据库，失败不报错。
  try {
    if (commandExists('update-desktop-database')) {
      await run('update-desktop-database', [dirname(file)], { allowFailure: true });
    }
  } catch {
    // Best effort.
  }
}

async function uninstallLinux(result: ShortcutResult): Promise<void> {
  const file = linuxDesktopFile();
  if (existsSync(file)) {
    rmrf(file);
    result.removed.push(file);
  }
}

function windowsLinkScript(link: string, target: string, args: string, icon: string): string {
  // 用 WScript.Shell 建 .lnk，不引入第三方依赖。
  return [
    `$shell = New-Object -ComObject WScript.Shell`,
    `$shortcut = $shell.CreateShortcut(${JSON.stringify(link)})`,
    `$shortcut.TargetPath = ${JSON.stringify(target)}`,
    `$shortcut.Arguments = ${JSON.stringify(args)}`,
    `$shortcut.WorkingDirectory = ${JSON.stringify(dirname(target))}`,
    `$shortcut.IconLocation = ${JSON.stringify(icon)}`,
    `$shortcut.Description = ${JSON.stringify('dsvm desktop (dsh web UI)')}`,
    `$shortcut.Save()`,
  ].join('\r\n');
}

async function installWindows(nwBinary: string, appDir: string, result: ShortcutResult): Promise<void> {
  const icon = existsSync(appIcon('ico')) ? appIcon('ico') : nwBinary;
  const startMenuDir = join(
    homedir(),
    'AppData',
    'Roaming',
    'Microsoft',
    'Windows',
    'Start Menu',
    'Programs',
    'dsvm desktop',
  );
  const desktopDir = join(homedir(), 'Desktop');
  mkdirp(startMenuDir);
  const links = [
    join(startMenuDir, 'dsvm desktop.lnk'),
    join(desktopDir, 'dsvm desktop.lnk'),
  ];
  for (const link of links) {
    mkdirp(dirname(link));
    await run('powershell', [
      '-NoProfile',
      '-NonInteractive',
      '-Command',
      windowsLinkScript(link, nwBinary, `"${appDir}"`, icon),
    ]);
    result.created.push(link);
  }
}

async function uninstallWindows(result: ShortcutResult): Promise<void> {
  const candidates = [
    join(
      homedir(),
      'AppData',
      'Roaming',
      'Microsoft',
      'Windows',
      'Start Menu',
      'Programs',
      'dsvm desktop',
    ),
    join(homedir(), 'Desktop', 'dsvm desktop.lnk'),
  ];
  for (const candidate of candidates) {
    if (existsSync(candidate)) {
      rmrf(candidate);
      result.removed.push(candidate);
    }
  }
}

/**
 * macOS：在 ~/Applications 下放一个最小 .app bundle（shell 可执行 + Info.plist），
 * 双击即以后台方式启动 nw。图标为最佳努力（缺 icns 工具链则用默认图标）。
 * 实在建不出来则抛错提示不支持，由上层如实转告用户。
 */
async function installMac(nwBinary: string, appDir: string, result: ShortcutResult): Promise<void> {
  const appBundle = join(homedir(), 'Applications', 'dsvm desktop.app');
  const macosDir = join(appBundle, 'Contents', 'MacOS');
  try {
    mkdirp(macosDir);
    const launcher = join(macosDir, 'dsvm-desktop');
    const quote = (value: string): string => `'${value.replace(/'/g, `'\\''`)}'`;
    writeFileSync(
      launcher,
      `#!/bin/sh\n# Generated by \`dsvm desktop install\`. Launches the cached nw.js SDK directly.\nexec ${quote(nwBinary)} ${quote(appDir)} "$@"\n`,
      { mode: 0o755 },
    );
    writeFileSync(
      join(appBundle, 'Contents', 'Info.plist'),
      [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">',
        '<plist version="1.0">',
        '<dict>',
        '  <key>CFBundleExecutable</key>',
        '  <string>dsvm-desktop</string>',
        '  <key>CFBundleIdentifier</key>',
        '  <string>dev.dsvm.desktop</string>',
        '  <key>CFBundleName</key>',
        `  <string>${APP_DISPLAY_NAME}</string>`,
        '  <key>CFBundlePackageType</key>',
        '  <string>APPL</string>',
        '  <key>LSUIElement</key>',
        '  <false/>',
        '</dict>',
        '</plist>',
        '',
      ].join('\n'),
    );
    result.created.push(appBundle);
    const png = appIcon('png');
    if (existsSync(png)) {
      result.notes.push(`macOS dock icon is the default one (custom icns not generated); app icon source: ${png}`);
    }
  } catch (error) {
    throw new DsvmError(
      `dsvm desktop install is not supported on this macOS setup (${(error as Error).message}); ` +
        'run `dsvm desktop` to launch the built-in nw.js app instead',
    );
  }
}

async function uninstallMac(result: ShortcutResult): Promise<void> {
  const appBundle = join(homedir(), 'Applications', 'dsvm desktop.app');
  if (existsSync(appBundle)) {
    rmrf(appBundle);
    result.removed.push(appBundle);
  }
  // 兼容早期版本可能写过的启动脚本。
  const legacy = join(homedir(), 'Applications', 'dsvm-desktop.sh');
  if (existsSync(legacy)) {
    rmrf(legacy);
    result.removed.push(legacy);
  }
}

export async function installShortcut(nwBinary: string, appDir?: string): Promise<ShortcutResult> {
  const dir = appDir ?? desktopAppDir();
  const result: ShortcutResult = { created: [], removed: [], notes: [] };
  if (process.platform === 'linux') {
    await installLinux(nwBinary, dir, result);
  } else if (process.platform === 'win32') {
    await installWindows(nwBinary, dir, result);
  } else if (process.platform === 'darwin') {
    await installMac(nwBinary, dir, result);
  } else {
    throw new DsvmError(
      `dsvm desktop install does not support platform "${process.platform}"; ` +
        'run `dsvm desktop` to launch the built-in nw.js app instead',
    );
  }
  return result;
}

export async function uninstallShortcut(): Promise<ShortcutResult> {
  const result: ShortcutResult = { created: [], removed: [], notes: [] };
  if (process.platform === 'linux') {
    await uninstallLinux(result);
  } else if (process.platform === 'win32') {
    await uninstallWindows(result);
  } else if (process.platform === 'darwin') {
    await uninstallMac(result);
  }
  // 未知平台：只做缓存清理，由调用方说明。
  return result;
}

/** 读文件小工具：给单测/诊断用，缺失返回 null 而不是抛错。 */
export function tryRead(file: string): string | null {
  try {
    return readFileSync(file, 'utf8');
  } catch {
    return null;
  }
}
